#!/usr/bin/env python3
"""Generate the harness block of every agent client pack from one source per pack.

A pack is a directory `integrations/<client>/` that holds `harness.src.md`, the single source of
the harness text, and a generated `harness.generated.md` next to it. The generated file wraps the
source, byte for byte, in markers, so an installer can replace the block in a client's instructions
file again and again. `--check` fails when a generated file is missing or differs from its source.

Every generated text is checked before it is written:
- each `lattice_*` name is a tool that `crates/lattice-sdk/src/mcp.rs` serves (the `Tool::X => "lattice_x"`
  arms of `fn name`), so a pack cannot name a removed tool;
- no email address, no absolute user path and no token-looking value.

Usage:
  python3 tools/gen_harness_packs.py          write the generated files
  python3 tools/gen_harness_packs.py --check  exit 1 when a generated file is missing or stale

The pure functions take their inputs as arguments and are unit tested in test_gen_harness_packs.py.
"""

import argparse
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
MCP_SOURCE = "crates/lattice-sdk/src/mcp.rs"
SOURCE_NAME = "harness.src.md"
OUTPUT_NAME = "harness.generated.md"
BEGIN_MARK = "<!-- BEGIN lattice harness: generated by tools/gen_harness_packs.py from harness.src.md; do not edit -->"
END_MARK = "<!-- END lattice harness -->"

ARM_RE = re.compile(r'Tool::[A-Za-z]+\s*=>\s*"(?P<name>lattice_[a-z_]+)"')
TOOL_NAME_RE = re.compile(r"\blattice_[a-z_]+\b")
EMAIL_RE = re.compile(r"[A-Za-z0-9._%+-]+@[A-Za-z0-9-]+\.[A-Za-z]{2,}")
ABS_PATH_RE = re.compile(r"/Users/|/home/|/root/|[A-Za-z]:\\Users\\")
SECRET_RE = re.compile(
    r"(?i)bearer\s+[A-Za-z0-9._~+/-]{16,}"
    r"|(?:token|secret|password|passwd|api[_-]?key)\s*[:=]\s*['\"]?[A-Za-z0-9._~+/-]{12,}"
)


def served_tool_names(mcp_source):
    """Return the wire names of the tools `fn name` maps, read from the Rust source text."""
    start = mcp_source.find("pub fn name(self)")
    if start < 0:
        raise ValueError(f"{MCP_SOURCE}: no `pub fn name(self)`, so the tool names cannot be read")
    end = mcp_source.find("\n    }\n", start)
    if end < 0:
        raise ValueError(f"{MCP_SOURCE}: `fn name` is not closed where expected")
    names = {m.group("name") for m in ARM_RE.finditer(mcp_source[start:end])}
    if not names:
        raise ValueError(f"{MCP_SOURCE}: `fn name` maps no tool")
    return names


def unknown_tool_names(text, served):
    """Return the `lattice_*` names in a text that the server does not serve, sorted."""
    return sorted(set(TOOL_NAME_RE.findall(text)) - served)


def hygiene_problems(text):
    """Return the reasons a text must not ship: an email, an absolute user path or a token."""
    problems = []
    if EMAIL_RE.search(text):
        problems.append("contains an email address")
    if ABS_PATH_RE.search(text):
        problems.append("contains an absolute user path")
    if SECRET_RE.search(text):
        problems.append("contains a token-looking value")
    return problems


def render(source, served, label):
    """Return the generated block for one source text, or raise ValueError naming the problem."""
    if BEGIN_MARK in source or END_MARK in source:
        raise ValueError(f"{label}: the source contains a generator marker")
    if not source.endswith("\n") or source.endswith("\n\n"):
        raise ValueError(f"{label}: the source must end with exactly one newline")
    problems = [f"names a tool the server does not serve: {n}" for n in unknown_tool_names(source, served)]
    problems += hygiene_problems(source)
    if problems:
        raise ValueError(f"{label}: " + "; ".join(problems))
    return f"{BEGIN_MARK}\n{source}{END_MARK}\n"


def discover_packs(root):
    """Return the pack directories under `integrations/`, those with a harness source, sorted."""
    return sorted(p.parent for p in (root / "integrations").glob(f"*/{SOURCE_NAME}"))


def build(root):
    """Return {generated path: expected text} for every pack under `root`. Raises ValueError."""
    mcp_path = root / MCP_SOURCE
    if not mcp_path.is_file():
        raise ValueError(f"{MCP_SOURCE} is missing")
    served = served_tool_names(mcp_path.read_text(encoding="utf-8"))
    packs = discover_packs(root)
    if not packs:
        raise ValueError(f"no integrations/*/{SOURCE_NAME} found")
    expected = {}
    for pack in packs:
        rel = pack.relative_to(root).as_posix()
        source = (pack / SOURCE_NAME).read_text(encoding="utf-8")
        expected[pack / OUTPUT_NAME] = render(source, served, f"{rel}/{SOURCE_NAME}")
    return expected


def drift_problems(root, expected):
    """Return one line per generated file that is missing or differs from its expected text."""
    problems = []
    for path, text in sorted(expected.items()):
        rel = path.relative_to(root).as_posix()
        if not path.is_file():
            problems.append(f"missing: {rel}")
        elif path.read_text(encoding="utf-8") != text:
            problems.append(f"stale: {rel}")
    return problems


def main(argv=None):
    parser = argparse.ArgumentParser(description="Generate harness packs from their sources.")
    parser.add_argument("--check", action="store_true", help="fail on drift instead of writing")
    args = parser.parse_args(argv)
    try:
        expected = build(REPO_ROOT)
    except (OSError, ValueError) as err:
        print(f"gen_harness_packs: {err}", file=sys.stderr)
        return 1
    if args.check:
        problems = drift_problems(REPO_ROOT, expected)
        for line in problems:
            print(line, file=sys.stderr)
        if problems:
            print("run: python3 tools/gen_harness_packs.py", file=sys.stderr)
            return 1
        return 0
    for path, text in sorted(expected.items()):
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(REPO_ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
