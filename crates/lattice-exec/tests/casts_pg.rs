#[test]
fn casts_and_formatting_agree_with_postgresql() {
    let mut f = fixture();
    let mut s = admin();
    for (sql, expected) in CASES {
        let got = match s.execute(&mut f.db, sql) {
            Ok(r) => text(&r)[0][0].clone(),
            Err(e) => format!("ERROR {}", e.sqlstate()),
        };
        assert_eq!(got, expected, "{sql}");
    }
}
